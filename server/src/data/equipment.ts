export const weapons: EquipmentItem[] = equipment.filter(e => e.type === 'weapon');
export const armors: EquipmentItem[] = equipment.filter(e => e.type === 'armor' || e.type === 'shield');
export const adventuringGear: EquipmentItem[] = equipment.filter(e => e.type === 'gear' || e.type === 'tool');

export function getEquipment(name: string): EquipmentItem | undefined {
  return equipment.find(e => e.name.toLowerCase() === name.toLowerCase());
}

export function getWeaponsByCategory(category: string): EquipmentItem[] {
  return weapons.filter(w => w.category.toLowerCase() === category.toLowerCase());
}

export function getArmorByType(type: string): EquipmentItem[] {
  return armors.filter(a => a.category.toLowerCase().includes(type.toLowerCase()));
}
