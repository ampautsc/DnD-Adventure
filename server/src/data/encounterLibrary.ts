export function getEncountersByDifficulty(
  difficulty: 'trivial' | 'easy' | 'medium' | 'hard' | 'deadly' | 'boss'
): LibraryEncounter[] {
  return encounterLibrary.filter((e) => e.difficulty === difficulty);
}

export function getEncountersForLevel(partyLevel: number): LibraryEncounter[] {
  return encounterLibrary.filter(
    (e) => e.minLevel <= partyLevel && e.maxLevel >= partyLevel
  );
}
