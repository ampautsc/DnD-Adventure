export function getSpell(name: string): Spell | undefined {
  return spells.find(
    (spell) => spell.name.toLowerCase() === name.toLowerCase()
  );
}

export function getSpellsByClass(className: string): Spell[] {
  return spells.filter((spell) =>
    spell.classes.some(
      (c) => c.toLowerCase() === className.toLowerCase()
    )
  );
}

export function getSpellsByLevel(level: number): Spell[] {
  return spells.filter((spell) => spell.level === level);
}
